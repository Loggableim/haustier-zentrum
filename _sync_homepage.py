#!/usr/bin/env python3
"""
_sync_homepage.py — Add missing articles to the homepage article grid.

The homepage has a static article grid (id="article-grid"). New articles
generated by the content factory are not automatically added. This script
finds articles on disk that are missing from the grid and appends cards
for them.

Usage: python _sync_homepage.py [--dry-run]
"""
import argparse
import html as htmllib
import re
from pathlib import Path

ROOT = Path(r"C:\sidekick\home\spaces\haustier-zentrum")
ART_DIR = ROOT / "artikel"
INDEX = ROOT / "index.html"


def get_meta(path: Path):
    """Extract title, description, category, date, image from an article."""
    h = path.read_text(encoding="utf-8")
    tm = re.search(r"<title>([^<]*)</title>", h)
    title = htmllib.unescape(tm.group(1)) if tm else path.stem
    title = title.split(" | ")[0]

    dm = re.search(r'<meta name="description" content="([^"]*)"', h)
    desc = htmllib.unescape(dm.group(1)) if dm else ""

    im = re.search(r'<img src="\.\./images/([^"]+)"', h)
    img = im.group(1) if im else ""

    # Category from JSON-LD articleSection
    cm = re.search(r'"articleSection":\s*\[([^\]]*)\]', h)
    cat = "allgemein"
    if cm:
        raw = cm.group(1).lower()
        if "hund" in raw:
            cat = "hunde"
        elif "katze" in raw:
            cat = "katzen"
        elif "kleintier" in raw or "hamster" in raw or "meerschwein" in raw or "kaninchen" in raw or "chinchilla" in raw:
            cat = "kleintiere"
        elif "vogel" in raw or "vögel" in raw:
            cat = "voegel"
        elif "aquarium" in raw:
            cat = "aquarium"

    # Date from JSON-LD
    dm2 = re.search(r'"datePublished":\s*"([^"]*)"', h)
    date_iso = dm2.group(1) if dm2 else ""
    date_display = ""
    if date_iso:
        try:
            from datetime import datetime
            d = datetime.strptime(date_iso[:10], "%Y-%m-%d")
            months = ["Januar", "Februar", "März", "April", "Mai", "Juni",
                      "Juli", "August", "September", "Oktober", "November", "Dezember"]
            date_display = f"{d.day}. {months[d.month-1]} {d.year}"
        except Exception:
            date_display = date_iso

    return {
        "slug": path.stem,
        "title": title,
        "desc": desc[:150],
        "img": img,
        "cat": cat,
        "date": date_display,
    }


def build_card(meta, index):
    title_esc = meta["title"].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    desc_esc = meta["desc"].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    img_tag = ""
    if meta["img"]:
        img_tag = (f'<div class="card-img"><img src="images/{meta["img"]}" '
                   f'alt="{title_esc}" loading="lazy"></div>')
    cat_label = {"hunde": "Hunde", "katzen": "Katzen", "kleintiere": "Kleintiere",
                 "voegel": "Vögel", "aquarium": "Aquarium", "allgemein": "Ratgeber"}[meta["cat"]]
    return f'''
    <article data-index="{index}" class="blog-card" data-cat="{meta["cat"]}">
      {img_tag}
      <div class="card-body">
        <div class="card-cats"><span>{cat_label}</span><span>Neu</span></div>
        <div class="card-date">{meta["date"]}</div>
        <h2><a href="/artikel/{meta["slug"]}">{title_esc}</a></h2>
        <p>{desc_esc}</p>
      </div>
    </article>'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    html = INDEX.read_text(encoding="utf-8")

    # Find the article grid section boundaries
    grid_id_pos = html.find('id="article-grid"')
    if grid_id_pos == -1:
        print("❌ article-grid not found")
        return 1
    grid_start = html.find(">", grid_id_pos) + 1

    # The grid ends at the closing </div> that follows the last </article>
    # inside the section. Find the section end first.
    section_end = html.find("</section>", grid_id_pos)
    if section_end == -1:
        print("❌ section end not found")
        return 1
    last_article = html.rfind("</article>", grid_id_pos, section_end)
    if last_article == -1:
        print("❌ no articles found in grid")
        return 1
    grid_end = html.find("</div>", last_article) + len("</div>")

    grid_html = html[grid_start:grid_end]
    linked = set(re.findall(r'href="/artikel/([A-Za-z0-9_\-]+)"', grid_html))
    print(f"  (grid slice: {len(grid_html)} chars, {len(linked)} unique links)")

    disk = {p.stem: p for p in ART_DIR.glob("*.html")}
    missing = [s for s in sorted(disk) if s not in linked]

    print(f"Articles on disk: {len(disk)}")
    print(f"Linked in grid: {len(linked)}")
    print(f"Missing: {len(missing)}")

    if not missing:
        print("✅ Homepage is in sync")
        return 0

    # Determine max data-index
    idxs = [int(x) for x in re.findall(r'data-index="(\d+)"', grid_html)]
    next_idx = max(idxs) + 1 if idxs else 0

    cards = []
    for slug in missing:
        meta = get_meta(disk[slug])
        cards.append(build_card(meta, next_idx))
        next_idx += 1
        print(f"  + {slug}")

    if args.dry_run:
        print(f"[dry-run] Would add {len(cards)} cards")
        return 0

    new_grid = grid_html.rstrip() + "\n" + "\n".join(cards) + "\n  "
    html = html[:grid_start] + new_grid + html[grid_end:]

    # Update the "98+" counter
    html = re.sub(r'<p>\d+\+ Ratgeber', f'<p>{len(disk)}+ Ratgeber', html)

    INDEX.write_text(html, encoding="utf-8")
    print(f"✅ Added {len(cards)} cards to homepage")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
