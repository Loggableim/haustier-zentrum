# Sort keys by length descending so longer compounds match first
SORTED_KEYS = sorted(MAPPING.keys(), key=len, reverse=True)

URL_RE = re.compile(r'(https?://[^\s"\'<>]+|/artikel/[A-Za-z0-9_\-]+)')


def fix_text(text: str) -> tuple[str, int]:
    """Apply replacements to a text fragment, protecting URLs."""
    changes = 0
    # Mask URLs
    urls = []

    def _mask(m):
        urls.append(m.group(0))
        return f"\x00URL{len(urls)-1}\x00"

    masked = URL_RE.sub(_mask, text)
    for key in SORTED_KEYS:
        if key in masked:
            n = masked.count(key)
            masked = masked.replace(key, MAPPING[key])
            changes += n
    # Unmask
    for i, u in enumerate(urls):
        masked = masked.replace(f"\x00URL{i}\x00", u)
    return masked, changes


def fix_file(path: Path, dry_run: bool) -> int:
    text = path.read_text(encoding="utf-8")
    changes = 0

    # Split into tags and text — only modify text outside of <...>
    parts = re.split(r'(<[^>]*>)', text)
    for i, part in enumerate(parts):
        if part.startswith('<'):
            continue
        new_part, n = fix_text(part)
        changes += n
        parts[i] = new_part

    text = ''.join(parts)
    if changes and not dry_run:
        path.write_text(text, encoding="utf-8")
    return changes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    total = 0
    for name in TARGETS:
        p = ART_DIR / name
        if not p.exists():
            print(f"SKIP (not found): {name}")
            continue
        c = fix_file(p, args.dry_run)
        print(f"{'[dry-run] ' if args.dry_run else ''}{name}: {c} replacements")
        total += c
    print(f"Total: {total}")


if __name__ == "__main__":
    main()
